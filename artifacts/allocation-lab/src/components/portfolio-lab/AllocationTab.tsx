import { useState } from "react";
import { useLocation } from "wouter";
import { useListDecisionLogs } from "@workspace/api-client-react";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { EmptyState } from "@/components/shared/EmptyState";
import { DetailDrawer } from "@/components/shared/DetailDrawer";
import {
  ShieldCheck, ShieldAlert, CheckCircle2, XCircle, Info,
  ArrowUpRight, ArrowDownRight, ClipboardList, Send, ExternalLink,
} from "lucide-react";
import { Link } from "wouter";
import type { RunResult, Constraints } from "@workspace/api-client-react";

interface Props {
  result: RunResult | undefined;
  constraints: Constraints | undefined;
  hasData: boolean;
  hasRun: boolean;
}

function pct(n: number, d = 1) {
  return `${(n * 100).toFixed(d)}%`;
}

function getCellColor(val: number) {
  if (val >= 80) return "bg-green-100 text-green-800";
  if (val >= 60) return "bg-green-50 text-green-700";
  if (val >= 40) return "bg-amber-50 text-amber-700";
  if (val >= 20) return "bg-red-50 text-red-700";
  return "bg-red-100 text-red-800";
}

interface ConstraintCheck {
  label: string;
  pass: boolean;
  required: string;
  actual: string;
  slack?: string;
  binding: boolean;
  detail?: string;
}

function EtfLink({ ticker }: { ticker: string }) {
  return (
    <Link href={`/etf/${ticker}`} className="inline-flex items-center gap-0.5 hover:text-primary hover:underline transition-colors group">
      {ticker}
      <ExternalLink className="h-2.5 w-2.5 opacity-0 group-hover:opacity-60 transition-opacity" />
    </Link>
  );
}

function SectionHeader({ title, description }: { title: string; description?: string }) {
  return (
    <div className="pt-4">
      <h2 className="text-base font-semibold text-gray-900">{title}</h2>
      {description && <p className="text-sm text-muted-foreground mt-0.5">{description}</p>}
      <div className="border-b border-gray-200 mt-3" />
    </div>
  );
}

export function AllocationTab({ result, constraints, hasData, hasRun }: Props) {
  const [, setLocation] = useLocation();
  const [etfDrawer, setEtfDrawer] = useState<NonNullable<typeof result>["allocations"][0] | null>(null);

  const sessionId = result?.sessionId;
  const { data: decisionLogs, isLoading: loadingDecisionLog } = useListDecisionLogs();
  const decisionLog = decisionLogs?.find(log => log.sessionId === sessionId);
  const tradeList = decisionLog?.content?.tradeList ?? [];
  const activeTrades = tradeList.filter((t: { action: string }) => t.action !== "HOLD");

  if (!hasData) return <EmptyState icon={ShieldCheck} title="Valid price history is required." description="Upload price data to audit constraints and view the final allocation." />;
  if (!hasRun || !result || !constraints) {
    return <EmptyState icon={ShieldCheck} title="Run Optimizer to generate the allocation." description="Constraint audit and final allocation are generated by the optimizer pipeline." />;
  }

  const allocs = result.allocations;
  const sortedAllocs = allocs.slice().sort((a, b) => b.weight - a.weight);
  const activeAllocs = allocs.filter((a) => a.active);
  const excluded = allocs.filter((a) => !a.active);
  const diag = result.diagnostics;

  // Build constraint checks
  const checks: ConstraintCheck[] = [
    {
      label: "Cash Minimum",
      pass: result.cashWeight >= constraints.cashMin - 0.0001,
      required: `≥ ${pct(constraints.cashMin)}`,
      actual: pct(result.cashWeight),
      slack: `${pct(result.cashWeight - constraints.cashMin)} slack`,
      binding: result.cashWeight - constraints.cashMin < 0.01,
      detail: "Cash must be at least this percentage to ensure liquidity buffer.",
    },
    {
      label: "Cash Maximum",
      pass: result.cashWeight <= constraints.cashMax + 0.0001,
      required: `≤ ${pct(constraints.cashMax)}`,
      actual: pct(result.cashWeight),
      slack: `${pct(constraints.cashMax - result.cashWeight)} slack`,
      binding: constraints.cashMax - result.cashWeight < 0.01,
      detail: "Cash ceiling prevents excessive defensiveness even in Risk-Off regimes.",
    },
    {
      label: "Max ETF Weight",
      pass: allocs.every((a) => a.weight <= constraints.maxEtfWeight + 0.0001),
      required: `≤ ${pct(constraints.maxEtfWeight)} per ETF`,
      actual: `max ${pct(Math.max(...allocs.map((a) => a.weight)))}`,
      slack: `${pct(constraints.maxEtfWeight - Math.max(...allocs.map((a) => a.weight)))} slack`,
      binding: Math.max(...allocs.map((a) => a.weight)) >= constraints.maxEtfWeight - 0.005,
      detail: "Maximum weight per individual ETF to prevent single-position concentration.",
    },
    {
      label: "Min Active ETFs",
      pass: result.activeEtfCount >= 8,
      required: "≥ 8 active ETFs",
      actual: `${result.activeEtfCount} active`,
      slack: `${result.activeEtfCount - 8} above floor`,
      binding: result.activeEtfCount === 8,
      detail: "Minimum breadth requirement. At least 8 non-zero positions required.",
    },
    {
      label: "Target Active ETFs",
      pass: result.activeEtfCount >= constraints.targetActiveEtfs,
      required: `≥ ${constraints.targetActiveEtfs} active`,
      actual: `${result.activeEtfCount} active`,
      slack: `${result.activeEtfCount - constraints.targetActiveEtfs} above target`,
      binding: result.activeEtfCount === constraints.targetActiveEtfs,
      detail: "Target number of actively allocated positions.",
    },
    {
      label: "Min Inclusion Threshold",
      pass: allocs.filter((a) => a.active).every((a) => a.weight >= constraints.minInclusionThreshold - 0.0001),
      required: `≥ ${pct(constraints.minInclusionThreshold)} if included`,
      actual: `min ${pct(Math.min(...allocs.filter((a) => a.active).map((a) => a.weight)))}`,
      binding: false,
      detail: "Positions must be 0% or at least this percentage. Eliminates insignificant allocations.",
    },
  ];

  const allPass = checks.every((c) => c.pass);
  const bindingCount = checks.filter((c) => c.binding && c.pass).length;
  const violationCount = checks.filter((c) => !c.pass).length;

  const unconstrainedTopByScore = allocs
    .slice()
    .sort((a, b) => b.factorScores.composite - a.factorScores.composite)
    .slice(0, constraints.targetActiveEtfs);
  const unconstrainedMissing = unconstrainedTopByScore.filter((a) => !a.active).map((a) => a.ticker);

  return (
    <div className="space-y-6">
      {/* ETF drilldown drawer */}
      <DetailDrawer
        open={!!etfDrawer}
        onOpenChange={(o) => !o && setEtfDrawer(null)}
        title={etfDrawer ? `${etfDrawer.ticker} — Allocation Detail` : ""}
      >
        {etfDrawer && (
          <div className="space-y-5 text-sm">
            <div>
              <h4 className="text-xs font-semibold uppercase tracking-wider text-muted-foreground mb-1">Position</h4>
              <p className="text-gray-700">{etfDrawer.name} · {etfDrawer.sector}</p>
            </div>
            <div className="grid grid-cols-2 gap-4">
              <div className="border rounded p-3">
                <p className="text-[10px] text-muted-foreground">Target Weight</p>
                <p className="text-2xl font-bold text-primary">{pct(etfDrawer.weight)}</p>
              </div>
              <div className="border rounded p-3">
                <p className="text-[10px] text-muted-foreground">Change vs Starting Weight</p>
                <p className={`text-2xl font-bold ${etfDrawer.change > 0 ? "text-green-600" : etfDrawer.change < 0 ? "text-red-600" : "text-gray-400"}`}>
                  {etfDrawer.change >= 0 ? "+" : ""}{pct(etfDrawer.change)}
                </p>
              </div>
            </div>
            <div>
              <h4 className="text-xs font-semibold uppercase tracking-wider text-muted-foreground mb-2">Factor Scores</h4>
              <div className="grid grid-cols-3 gap-2">
                {[
                  { label: "Composite", val: etfDrawer.factorScores.composite },
                  { label: "Mom 20D",   val: etfDrawer.factorScores.mom20 },
                  { label: "Mom 60D",   val: etfDrawer.factorScores.mom60 },
                  { label: "Mom 120D",  val: etfDrawer.factorScores.mom120 },
                  { label: "Mom 252D",  val: etfDrawer.factorScores.mom252 },
                  { label: "Trend Q",   val: etfDrawer.factorScores.trendQuality },
                  { label: "Vol 60D",   val: etfDrawer.factorScores.realizedVol60 },
                  { label: "Drawdown",  val: etfDrawer.factorScores.drawdown },
                  { label: "MeanRev",   val: etfDrawer.factorScores.meanReversion },
                ].map(({ label, val }) => (
                  <div key={label} className={`text-center text-xs font-medium rounded px-2 py-1.5 ${getCellColor(val)}`}>
                    <p className="text-[10px] opacity-70">{label}</p>
                    <p className="font-bold">{val.toFixed(0)}</p>
                  </div>
                ))}
              </div>
            </div>
            {diag.riskContributions.find((r) => r.ticker === etfDrawer.ticker) && (
              <div>
                <h4 className="text-xs font-semibold uppercase tracking-wider text-muted-foreground mb-2">Risk Contribution</h4>
                <div className="border rounded p-3">
                  <p className="text-2xl font-bold text-gray-900">
                    {pct(diag.riskContributions.find((r) => r.ticker === etfDrawer.ticker)!.riskContributionPct)}
                  </p>
                  <p className="text-[11px] text-muted-foreground">of total portfolio risk</p>
                </div>
              </div>
            )}
            <div>
              <h4 className="text-xs font-semibold uppercase tracking-wider text-muted-foreground mb-2">
                {etfDrawer.active ? "Inclusion Rationale" : "Exclusion Rationale"}
              </h4>
              <div className={`border rounded p-3 text-xs ${etfDrawer.active ? "bg-green-50 border-green-200 text-green-800" : "bg-gray-50 border-gray-200 text-gray-600"}`}>
                {etfDrawer.active
                  ? `Composite factor score ${etfDrawer.factorScores.composite.toFixed(0)}/100 ranks this ETF within the top selection. All inclusion constraints satisfied.`
                  : `Composite score ${etfDrawer.factorScores.composite.toFixed(0)}/100 below the active selection threshold, or excluded by minimum-inclusion or target-active-ETF constraints.`
                }
              </div>
            </div>
            <Button variant="outline" size="sm" asChild>
              <Link href={`/etf/${etfDrawer.ticker}`}>
                Open ETF Explorer <ExternalLink className="ml-1.5 h-3 w-3" />
              </Link>
            </Button>
          </div>
        )}
      </DetailDrawer>

      {/* ════════════════════════════════════════
          SECTION 1 — CONSTRAINTS
      ════════════════════════════════════════ */}
      <SectionHeader title="Constraint Audit" description="Feasibility check, binding constraints, and slack for each institutional constraint." />

      {/* Feasibility summary */}
      <div className={`flex items-center gap-3 rounded-lg border px-5 py-4 ${allPass ? "border-green-200 bg-green-50" : "border-red-200 bg-red-50"}`}>
        {allPass
          ? <ShieldCheck className="h-5 w-5 text-green-600 shrink-0" />
          : <ShieldAlert className="h-5 w-5 text-red-600 shrink-0" />
        }
        <div>
          <p className={`text-sm font-semibold ${allPass ? "text-green-800" : "text-red-800"}`}>
            {allPass ? "All constraints satisfied — allocation is feasible." : "One or more constraints violated — allocation may not be compliant."}
          </p>
          <p className={`text-xs ${allPass ? "text-green-600" : "text-red-600"}`}>
            {bindingCount} binding · {violationCount} violation{violationCount !== 1 ? "s" : ""}
          </p>
        </div>
      </div>

      {/* Constraint audit table */}
      <Card>
        <CardContent className="overflow-x-auto pt-4">
          <Table>
            <TableHeader className="bg-gray-50">
              <TableRow>
                <TableHead className="text-xs">Constraint</TableHead>
                <TableHead className="text-xs">Required</TableHead>
                <TableHead className="text-xs">Actual</TableHead>
                <TableHead className="text-xs">Slack</TableHead>
                <TableHead className="text-xs text-center">Binding</TableHead>
                <TableHead className="text-xs text-center">Status</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {checks.map((c) => (
                <TableRow key={c.label} className={!c.pass ? "bg-red-50/40" : c.binding ? "bg-amber-50/30" : ""}>
                  <TableCell className="text-xs font-medium">
                    <div>{c.label}</div>
                    {c.detail && <div className="text-[10px] text-muted-foreground mt-0.5 max-w-48 leading-relaxed">{c.detail}</div>}
                  </TableCell>
                  <TableCell className="text-xs text-gray-700">{c.required}</TableCell>
                  <TableCell className={`text-xs font-semibold ${c.pass ? "text-gray-800" : "text-red-700"}`}>{c.actual}</TableCell>
                  <TableCell className="text-xs text-muted-foreground">{c.slack ?? "—"}</TableCell>
                  <TableCell className="text-xs text-center">
                    {c.binding
                      ? <Badge variant="outline" className="text-[10px] bg-amber-50 text-amber-700 border-amber-200">Binding</Badge>
                      : <span className="text-muted-foreground text-[10px]">—</span>
                    }
                  </TableCell>
                  <TableCell className="text-center">
                    {c.pass
                      ? <CheckCircle2 className="h-4 w-4 text-green-600 inline" />
                      : <XCircle className="h-4 w-4 text-red-600 inline" />
                    }
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </CardContent>
      </Card>

      {/* Included / excluded */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        <Card>
          <CardHeader className="pb-2">
            <CardTitle className="text-sm font-semibold flex items-center gap-2">
              <CheckCircle2 className="h-4 w-4 text-green-600" /> Included ({activeAllocs.length})
            </CardTitle>
          </CardHeader>
          <CardContent>
            <div className="space-y-1.5">
              {activeAllocs.slice().sort((a, b) => b.weight - a.weight).map((a) => (
                <div key={a.ticker} className="flex items-center justify-between text-xs">
                  <span className="font-medium text-gray-800">{a.ticker}</span>
                  <div className="flex items-center gap-2">
                    <span className="text-muted-foreground text-[10px]">score {a.factorScores.composite.toFixed(0)}</span>
                    <span className="font-semibold text-primary tabular-nums">{pct(a.weight)}</span>
                  </div>
                </div>
              ))}
            </div>
          </CardContent>
        </Card>
        <Card>
          <CardHeader className="pb-2">
            <CardTitle className="text-sm font-semibold flex items-center gap-2">
              <XCircle className="h-4 w-4 text-gray-400" /> Excluded ({excluded.length})
            </CardTitle>
          </CardHeader>
          <CardContent>
            {excluded.length === 0 ? (
              <p className="text-xs text-muted-foreground">All universe ETFs are included in the active allocation.</p>
            ) : (
              <div className="space-y-1.5">
                {excluded.slice().sort((a, b) => b.factorScores.composite - a.factorScores.composite).map((a) => (
                  <div key={a.ticker} className="flex items-center justify-between text-xs">
                    <span className="font-medium text-gray-500">{a.ticker}</span>
                    <div className="flex items-center gap-2">
                      <span className="text-muted-foreground text-[10px]">score {a.factorScores.composite.toFixed(0)}</span>
                      <Badge variant="outline" className="text-[10px] text-gray-400">
                        {a.factorScores.composite < 40 ? "Low score" : "Threshold / Cap"}
                      </Badge>
                    </div>
                  </div>
                ))}
              </div>
            )}
          </CardContent>
        </Card>
      </div>

      {unconstrainedMissing.length > 0 && (
        <Card className="border-amber-200 bg-amber-50/30">
          <CardHeader className="pb-2">
            <CardTitle className="text-sm font-semibold text-amber-800">Constraint Impact</CardTitle>
            <CardDescription className="text-amber-700">
              ETFs that rank in the top {constraints.targetActiveEtfs} by factor score but are excluded by constraints:
            </CardDescription>
          </CardHeader>
          <CardContent>
            <div className="flex gap-2 flex-wrap">
              {unconstrainedMissing.map((t) => (
                <Badge key={t} variant="outline" className="text-[10px] bg-white text-amber-700 border-amber-200">{t}</Badge>
              ))}
            </div>
            <p className="text-xs text-muted-foreground mt-3">
              Constraints are not silently altered. The unconstrained solution includes these positions; the constrained solution excludes them. Tracked in the governance audit log.
            </p>
          </CardContent>
        </Card>
      )}

      <Card className="border-dashed">
        <CardContent className="py-4">
          <div className="flex items-start gap-2 text-xs text-muted-foreground">
            <Info className="h-3.5 w-3.5 shrink-0 mt-0.5" />
            <div className="space-y-1">
              <p><strong>Default Institutional Constraints:</strong> Cash 50–60% · Max ETF weight 10% · Position is 0% or ≥ min-inclusion-threshold · Target 8 active ETFs.</p>
              <p>Constraints are configurable and versioned in Settings → Constraints.</p>
            </div>
          </div>
        </CardContent>
      </Card>

      {/* ════════════════════════════════════════
          SECTION 2 — FINAL ALLOCATION
      ════════════════════════════════════════ */}
      <SectionHeader title="Final Allocation" description="Ensemble portfolio weights, trade list, and routing to Investment Committee." />

      {/* Ensemble formula */}
      <Card className="border-blue-100 bg-blue-50/30">
        <CardContent className="py-4">
          <div className="flex items-start gap-3">
            <Info className="h-4 w-4 shrink-0 mt-0.5 text-blue-500" />
            <div className="text-xs space-y-2">
              <p className="font-semibold text-blue-800">Ensemble Portfolio Formula</p>
              <pre className="font-mono text-[10px] bg-white border border-blue-100 rounded px-3 py-2 text-blue-900 whitespace-pre">
{`w_final = α_momentum × w_momentum
         + α_minvar   × w_minvar
         + α_riskparity × w_riskparity

Current: α_momentum = 1.00 (sole computed model)
         α_minvar = 0.00  (extension required)
         α_riskparity = 0.00  (extension required)`}
              </pre>
            </div>
          </div>
        </CardContent>
      </Card>

      {/* Full allocation table */}
      <Card>
        <CardHeader>
          <CardTitle className="text-sm font-semibold">Full Universe</CardTitle>
          <CardDescription>Click any row to inspect factor scores, risk contribution, and trade rationale.</CardDescription>
        </CardHeader>
        <CardContent className="overflow-x-auto p-0">
          <Table>
            <TableHeader className="bg-gray-50 sticky top-0">
              <TableRow>
                <TableHead className="text-[10px]">Ticker</TableHead>
                <TableHead className="text-[10px]">Name</TableHead>
                <TableHead className="text-[10px] text-center">Score</TableHead>
                <TableHead className="text-[10px] text-right">Starting weight</TableHead>
                <TableHead className="text-[10px] text-right">Target</TableHead>
                <TableHead className="text-[10px] text-right">Δ</TableHead>
                <TableHead className="text-[10px] text-center">Risk Contrib.</TableHead>
                <TableHead className="text-[10px] text-center">Status</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              <TableRow className="bg-primary/5 font-medium border-b-2 border-primary/20">
                <TableCell className="text-xs font-bold">CASH</TableCell>
                <TableCell className="text-xs text-muted-foreground">Cash Reserve</TableCell>
                <TableCell className="text-xs text-center">—</TableCell>
                <TableCell className="text-xs text-right">{pct(result.cashPriorWeight)}</TableCell>
                <TableCell className="text-xs text-right font-bold text-primary">{pct(result.cashWeight)}</TableCell>
                <TableCell className={`text-xs text-right ${result.cashChange > 0 ? "text-green-600" : result.cashChange < 0 ? "text-red-600" : "text-gray-400"}`}>
                  {result.cashChange > 0 ? "+" : ""}{pct(result.cashChange)}
                </TableCell>
                <TableCell className="text-xs text-center">—</TableCell>
                <TableCell className="text-xs text-center"><Badge variant="outline" className="text-[10px] bg-gray-50">RESERVE</Badge></TableCell>
              </TableRow>
              {sortedAllocs.map((etf) => {
                const rc = diag.riskContributions.find((r) => r.ticker === etf.ticker);
                return (
                  <TableRow
                    key={etf.ticker}
                    className={`cursor-pointer hover:bg-gray-50/80 border-b border-gray-100 ${!etf.active ? "opacity-55" : ""}`}
                    onClick={() => setEtfDrawer(etf as any)}
                  >
                    <TableCell className="text-xs font-semibold text-primary">
                      <EtfLink ticker={etf.ticker} />
                    </TableCell>
                    <TableCell className="text-xs text-gray-600 max-w-28 truncate">{etf.name}</TableCell>
                    <TableCell className={`text-xs text-center font-bold ${getCellColor(etf.factorScores.composite)}`}>
                      {etf.factorScores.composite.toFixed(0)}
                    </TableCell>
                    <TableCell className="text-xs text-right text-muted-foreground">{pct(etf.priorWeight)}</TableCell>
                    <TableCell className={`text-xs text-right font-semibold ${etf.active ? "text-gray-900" : "text-gray-400"}`}>
                      {pct(etf.weight)}
                    </TableCell>
                    <TableCell className={`text-xs text-right ${Math.abs(etf.change) > 0.001 ? etf.change > 0 ? "text-green-600" : "text-red-600" : "text-gray-400"}`}>
                      {Math.abs(etf.change) > 0.001 ? (etf.change > 0 ? "+" : "") + pct(etf.change) : "—"}
                    </TableCell>
                    <TableCell className="text-xs text-center text-muted-foreground">
                      {rc ? pct(rc.riskContributionPct) : "—"}
                    </TableCell>
                    <TableCell className="text-xs text-center">
                      <Badge variant="outline" className={etf.active ? "text-[10px] bg-green-50 text-green-700 border-green-200" : "text-[10px] text-gray-400 border-gray-200"}>
                        {etf.active ? "ACTIVE" : "OUT"}
                      </Badge>
                    </TableCell>
                  </TableRow>
                );
              })}
            </TableBody>
          </Table>
        </CardContent>
      </Card>

      {/* Trade list */}
      <Card>
        <CardHeader className="pb-2">
          <CardTitle className="text-sm font-semibold flex items-center gap-2">
            <ClipboardList className="h-4 w-4 text-primary" /> Trade List
          </CardTitle>
          <CardDescription>Execution list implied by this rebalance. Committee approval in Investment Committee.</CardDescription>
        </CardHeader>
        <CardContent>
          {loadingDecisionLog ? (
            <p className="text-xs text-muted-foreground py-3">Loading the saved decision-log trade list…</p>
          ) : !decisionLog ? (
            <p className="text-xs text-muted-foreground py-3">
              No saved trade list exists yet. <Link href="/investment-committee" className="underline">Start review in Investment Committee</Link> to create a decision draft explicitly.
            </p>
          ) : activeTrades.length === 0 ? (
            <p className="text-xs text-muted-foreground py-3">No active trades — run a rebalance to generate the trade list.</p>
          ) : (
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead className="text-xs">Ticker</TableHead>
                  <TableHead className="text-xs">Action</TableHead>
                  <TableHead className="text-xs text-right">From</TableHead>
                  <TableHead className="text-xs text-right">To</TableHead>
                  <TableHead className="text-xs text-right">Δ Weight</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {activeTrades.map((t: any) => {
                  const delta = (t.toWeight ?? 0) - (t.fromWeight ?? 0);
                  return (
                    <TableRow key={t.ticker}>
                      <TableCell className="text-xs font-medium">{t.ticker}</TableCell>
                      <TableCell className="text-xs">
                        <Badge variant="outline" className={
                          t.action === "BUY" || t.action === "ADD" || t.action === "INCREASE"
                            ? "text-[10px] bg-green-50 text-green-700 border-green-200"
                            : t.action === "SELL" || t.action === "REMOVE" || t.action === "DECREASE"
                            ? "text-[10px] bg-red-50 text-red-700 border-red-200"
                            : "text-[10px]"
                        }>
                          {t.action}
                        </Badge>
                      </TableCell>
                      <TableCell className="text-xs text-right text-muted-foreground">{t.fromWeight !== undefined ? pct(t.fromWeight) : "—"}</TableCell>
                      <TableCell className="text-xs text-right font-semibold">{t.toWeight !== undefined ? pct(t.toWeight) : "—"}</TableCell>
                      <TableCell className={`text-xs text-right font-semibold ${delta > 0 ? "text-green-600" : delta < 0 ? "text-red-600" : "text-gray-400"}`}>
                        {Math.abs(delta) > 0.0001 ? (delta > 0 ? "+" : "") + pct(delta) : "—"}
                      </TableCell>
                    </TableRow>
                  );
                })}
              </TableBody>
            </Table>
          )}
        </CardContent>
      </Card>

      {/* Send to committee */}
      <Card className="border-l-4 border-l-primary">
        <CardContent className="py-4 flex items-center justify-between gap-4 flex-wrap">
          <div className="flex items-center gap-3">
            <Send className="h-5 w-5 text-primary shrink-0" />
            <div>
              <p className="text-sm font-medium text-gray-900">Ready to route this allocation to the Investment Committee?</p>
              <p className="text-xs text-muted-foreground mt-0.5">
                Final evidence package — backtest integrity, robustness, risk, and decision log — awaits committee review.
              </p>
            </div>
          </div>
          <Button size="sm" onClick={() => setLocation("/investment-committee")}>
            Open Investment Committee <ArrowUpRight className="ml-1.5 h-3.5 w-3.5" />
          </Button>
        </CardContent>
      </Card>
    </div>
  );
}
